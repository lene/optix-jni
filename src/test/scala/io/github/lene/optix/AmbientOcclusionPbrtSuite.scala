package io.github.lene.optix

import java.io.File
import java.io.FileInputStream
import java.io.PrintWriter
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.zip.GZIPInputStream

import menger.common.Color
import menger.common.ImageSize
import menger.common.Vector
import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers

/** The ambient occlusion factor against pbrt-v4's `ambientocclusion` integrator (optix-jni#106).
  *
  * The scene is a level-1 Menger sponge (20 cubes) on a floor, in
  * `test-resources/ambient-occlusion-pbrt/sponge-on-floor.pbrt` for pbrt and built here for
  * optix-jni. With the direct light off and every surface white, a pixel is the ambient fill
  * (0.3) times the occlusion factor, so the factor is read back from the render and compared per
  * pixel with pbrt's (cosine-weighted, unlimited distance). The committed pbrt reference is
  * regenerated by `render-pbrt-reference.sh`; a per-pixel error map goes to
  * `target/oj106-pbrt/`.
  *
  * Pixels at a geometric edge are left out: pbrt averages over the pixel's area, optix-jni takes
  * one ray through its centre, so they differ there by construction and not by the model.
  */
class AmbientOcclusionPbrtSuite extends AnyFlatSpec with Matchers with RendererFixture:

  OptiXRenderer.isLibraryLoaded shouldBe true

  private val imageSize = ImageSize(400, 300)
  private val ambientFill = 0.3f
  private val resources = new File("test-resources/ambient-occlusion-pbrt")
  private val outDir = new File("target/oj106-pbrt")

  // Error bounds, measured 0.0135 mean, 0.034 at the 95th percentile and -0.002 bias with some
  // margin. What remains is the 8-bit quantisation of the render (a factor is known to 1/76.5),
  // pbrt's own noise (4096 samples per pixel), and the pixels beside edges, where pbrt averages
  // over the pixel's area and optix-jni takes its centre.
  private val maxMeanError = 0.018
  private val max95thError = 0.04
  private val maxBias = 0.006
  private val edgeRange = 0.15  // a 5x5 neighbourhood spanning more than this is an edge

  private final case class Factors(values: Array[Float]):
    def at(x: Int, y: Int): Float = values(y * imageSize.width + x)

  /** The first channel of a PFM: three header lines ("PF", "w h", scale), then the rows bottom
    * first, in the byte order the sign of the scale gives. */
  private def readPfm(file: File): Factors =
    val in = new GZIPInputStream(new FileInputStream(file))
    val bytes = try in.readAllBytes() finally in.close()
    val headerEnd = bytes.indices.filter(bytes(_) == '\n'.toByte).apply(2)
    val Array(magic, w, h, scale) = new String(bytes, 0, headerEnd, "US-ASCII").trim.split("\\s+")
    magic shouldBe "PF"
    (w.toInt, h.toInt) shouldBe ((imageSize.width, imageSize.height))
    val order = if scale.toFloat < 0 then ByteOrder.LITTLE_ENDIAN else ByteOrder.BIG_ENDIAN
    val data = ByteBuffer.wrap(bytes, headerEnd + 1, bytes.length - headerEnd - 1).order(order)
    val rowFloats = imageSize.width * 3
    Factors(Array.tabulate(imageSize.width * imageSize.height): i =>
      val (x, y) = (i % imageSize.width, i / imageSize.width)
      data.getFloat(headerEnd + 1 + ((imageSize.height - 1 - y) * rowFloats + x * 3) * 4))

  private def renderFactors(): Factors =
    val cx = 1f / 3f
    renderer.clearPlanes()
    renderer.updateImageDimensions(imageSize)
    renderer.setCamera(Vector[3](-1.6f, 1.4f, 2.2f), Vector[3](0f, -0.1f, 0f), Vector[3](0f, 1f, 0f), 60f)
    renderer.setLight(Vector[3](0f, -1f, 0f), 0.0f)
    val white = Material.matte(Color(1f, 1f, 1f))
    renderer.addPlaneInstance(Vector[3](0f, 1f, 0f), -0.5f, white)
    renderer.setTriangleMesh(TestUtilities.createUnitCubeMesh())
    for i <- -1 to 1; j <- -1 to 1; k <- -1 to 1 if math.abs(i) + math.abs(j) + math.abs(k) > 1 do
      renderer.addTriangleMeshInstance(
        Array(cx, 0f, 0f, i * cx, 0f, cx, 0f, j * cx, 0f, 0f, cx, k * cx), white, TextureIndex.NoTexture)
    renderer.setAmbient(AmbientModel.Occlusion(samples = 16))
    renderer.setAccumulationFrames(128)  // averages the frames' sampling noise away
    val img = renderer.renderWithStats(imageSize).get().image
    // Truncated to a byte in the shader and again after averaging the frames: a level back.
    Factors(Array.tabulate(imageSize.width * imageSize.height)(i =>
      ((img(i * 4) & 0xff) + 1.0f) / (ambientFill * 255f)))

  private def isInterior(f: Factors, x: Int, y: Int): Boolean =
    val ns = for dy <- -2 to 2; dx <- -2 to 2 yield f.at(x + dx, y + dy)
    ns.max - ns.min < edgeRange

  "The ambient occlusion factor" should "match pbrt's ambientocclusion integrator pixel by pixel" in:
    val pbrt = readPfm(new File(resources, "sponge-on-floor_400x300.pfm.gz"))
    val optix = renderFactors()
    val interior = (for
      y <- 2 until imageSize.height - 2; x <- 2 until imageSize.width - 2
      if isInterior(pbrt, x, y) && isInterior(optix, x, y)
    yield (x, y)).toVector
    val errors = interior.map { case (x, y) => optix.at(x, y) - pbrt.at(x, y) }
    val absolute = errors.map(e => math.abs(e.toDouble)).sorted
    val mean = absolute.sum / absolute.size
    val p95 = absolute((absolute.size * 0.95).toInt)
    val bias = errors.sum.toDouble / errors.size
    val summary = f"${interior.size} of ${imageSize.width * imageSize.height} pixels compared; " +
      f"mean |error| $mean%.4f, 95th percentile $p95%.4f, bias (optix - pbrt) $bias%+.4f"
    info(summary)
    writeErrorMap(pbrt, optix, summary)
    interior.size should be > imageSize.width * imageSize.height / 2
    mean should be < maxMeanError
    p95 should be < max95thError
    math.abs(bias) should be < maxBias

  /** Writes the factors of both renders and their per-pixel error (x8, white = error 1/8). */
  private def writeErrorMap(pbrt: Factors, optix: Factors, summary: String): Unit =
    outDir.mkdirs()
    def gray(f: Int => Float): Array[Byte] =
      val img = new Array[Byte](imageSize.width * imageSize.height * 4)
      for i <- 0 until imageSize.width * imageSize.height do
        val v = (math.min(math.max(f(i), 0f), 1f) * 255f).toInt.toByte
        img(i * 4) = v; img(i * 4 + 1) = v; img(i * 4 + 2) = v; img(i * 4 + 3) = -1
      img
    def save(name: String, img: Array[Byte]): Unit =
      TestUtilities.savePNG(new File(outDir, name).getPath, img, imageSize.width, imageSize.height).get
    save("ao-pbrt.png", gray(pbrt.values(_)))
    save("ao-optix.png", gray(optix.values(_)))
    save("ao-error-x8.png", gray(i => math.abs(optix.values(i) - pbrt.values(i)) * 8f))
    val w = new PrintWriter(new File(outDir, "ao-vs-pbrt.txt"))
    try w.println(summary) finally w.close()
